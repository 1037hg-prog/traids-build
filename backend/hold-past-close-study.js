#!/usr/bin/env node
/**
 * SHOULD WINNERS RUN PAST THE CLOSE? (2026-09-09)
 *
 * WHERE THIS CAME FROM. 66% of the clean era's exits are "close" — the end-of-session flatten — at
 * an average win of +0.247R against an average loss of -0.216R. That is noise harvested at a random
 * point: symmetric outcomes from an arbitrary exit time. Only 1.4% of tickets ever reached a target,
 * and the ratchet armed once in 201 tickets because almost nothing lives long enough to trail. The
 * operator's reading: let winners run past the close.
 *
 * IT IS A REAL PROPOSAL AND IT IS TESTABLE, so it gets measured rather than agreed with.
 *
 * TWO VERSIONS, BECAUSE ONLY ONE OF THEM IS IMPLEMENTABLE
 *   HOLD ALL      extend every close-flattened ticket by N sessions. This is the honest upper bound
 *                 on "stop flattening", because at 15:55 you do not know which ones are winners.
 *   HOLD WINNERS  extend only the tickets that were GREEN at the close. This is the actual proposal
 *                 — a rule you could run tomorrow, since being green at the close is observable.
 *
 * MEASURED IN R, against each ticket's own stop distance, so it is comparable with everything else
 * on the board. Cost does NOT change between the arms: the position is opened and closed once either
 * way, so extending the hold adds no round trip. The comparison is therefore cost-neutral and the
 * baseline is what the book actually booked.
 *
 * CLUSTERING: the SESSION. Every ticket flattened on one day shares that day's overnight tape, which
 * is exactly the lesson the 08-21 fan-out taught — 41 tickets in one basket are one bet. n is
 * sessions, never tickets.
 *
 * EXPLORATORY AND WEIGHTLESS. The hypothesis was generated by looking at these same exits, so this
 * is motivating evidence only. If it looks good the honest next step is a REGISTERED forward test
 * with an evidence start in the future — not a rule change on the strength of a backward look.
 *
 * Usage: node backend/hold-past-close-study.js [--days 1,3,5] [--json]
 */
const path = require("path");
const R = require("./lib/reconcile.js");
const { nullBar } = require("./lib/null-bar.js");
const { writeJsonAtomic } = require("./lib/atomic-write.js");

const argv = process.argv.slice(2);
const arg = (k, d) => { const i = argv.indexOf(k); return i >= 0 ? argv[i + 1] : d; };
const HORIZONS = String(arg("--days", "1,3,5")).split(",").map(Number).filter(Number.isFinite);
const API = process.env.TRAIDS_API || "http://localhost:3001";

const mean = (a) => (a.length ? a.reduce((s, x) => s + x, 0) / a.length : NaN);
const sd = (a) => { if (a.length < 2) return NaN; const m = mean(a); return Math.sqrt(a.reduce((s, x) => s + (x - m) ** 2, 0) / (a.length - 1)); };
const tOf = (a) => { const s = sd(a); return s > 0 ? mean(a) / (s / Math.sqrt(a.length)) : NaN; };
const r3 = (x) => (Number.isFinite(x) ? +x.toFixed(3) : null);
const etDay = (ms) => new Date(ms).toLocaleDateString("en-CA", { timeZone: "America/New_York" });

(async () => {
  const L = R.cleanEraLedger();
  // Only rows the counterfactual can actually be computed for: a real exit price, a real stop
  // distance to divide by, and an equity symbol we can fetch daily bars for.
  const closed = (L.signals || []).filter((t) =>
    t.reason === "close" && t.cls === "Equity" &&
    Number.isFinite(t.exit) && Number.isFinite(t.stopDist) && t.stopDist > 0 && Number.isFinite(t.closedAt));
  if (!closed.length) { console.error("no close-flattened equity rows to test"); process.exit(1); }

  const syms = [...new Set(closed.map((t) => t.sym))];
  let data = {};
  try {
    data = (await fetch(`${API}/api/equities/bars`, { method: "POST", headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ symbols: syms, days: 120 }), signal: AbortSignal.timeout(180000) }).then((r) => r.json())).data || {};
  } catch (e) { console.error("bars fetch failed:", e.message); process.exit(1); }

  const dayOf = (b) => String(b.t).slice(0, 10);
  const rows = [];
  for (const t of closed) {
    const bars = data[t.sym] || [];
    const dates = bars.map(dayOf);
    const i = dates.indexOf(etDay(t.closedAt));
    if (i < 0) continue;
    const rec = { sym: t.sym, session: etDay(t.closedAt), bookedR: t.rMult, green: t.rMult > 0, ext: {} };
    for (const h of HORIZONS) {
      const j = i + h;
      if (j >= bars.length) continue;
      // R measured from the SAME entry and the SAME stop distance the ticket actually used
      rec.ext[h] = ((bars[j].c - t.entry) * t.dir) / t.stopDist;
    }
    if (Object.keys(rec.ext).length) rows.push(rec);
  }
  if (!rows.length) { console.error("no rows survived the bar join"); process.exit(1); }

  // session-clustered delta: (what holding would have made) - (what we booked)
  const arm = (subset, h) => {
    const use = subset.filter((r) => Number.isFinite(r.ext[h]));
    if (use.length < 10) return null;
    const byDay = {};
    for (const r of use) (byDay[r.session] ||= []).push(r.ext[h] - r.bookedR);
    const sess = Object.keys(byDay).sort().map((d) => mean(byDay[d]));
    if (sess.length < 3) return null;
    const bar = nullBar({ variants: 1, n: sess.length, trials: 20000 }).p95;
    return { tickets: use.length, sessions: sess.length, deltaR: r3(mean(sess)), t: r3(tOf(sess)), bar: r3(bar),
      clears: tOf(sess) >= bar && mean(sess) > 0,
      bookedR: r3(mean(use.map((r) => r.bookedR))), heldR: r3(mean(use.map((r) => r.ext[h]))) };
  };

  const greens = rows.filter((r) => r.green), reds = rows.filter((r) => !r.green);
  const out = { spec: "hold-past-close-v1", asOf: new Date().toISOString(),
    status: "EXPLORATORY — the hypothesis came from these same exits; carries no weight",
    population: { closeFlattenedEquityRows: rows.length, greenAtClose: greens.length, redAtClose: reds.length,
      sessions: new Set(rows.map((r) => r.session)).size },
    note: "Cost is identical in both arms — one round trip either way — so extending the hold adds no charge and the comparison is cost-neutral.",
    holdAll: {}, holdWinners: {}, holdLosers: {} };
  for (const h of HORIZONS) {
    out.holdAll[`+${h}d`] = arm(rows, h);
    out.holdWinners[`+${h}d`] = arm(greens, h);
    out.holdLosers[`+${h}d`] = arm(reds, h);
  }
  writeJsonAtomic(path.join(__dirname, "data", "hold-past-close.json"), out);
  if (argv.includes("--json")) { console.log(JSON.stringify(out, null, 1)); return; }

  console.log(`\n  HOLD PAST THE CLOSE — ${rows.length} close-flattened equity tickets across ${out.population.sessions} sessions`);
  console.log(`  ${greens.length} were green at the close, ${reds.length} were red. Cost is unchanged by holding, so this is a clean comparison.\n`);
  const show = (label, block) => {
    console.log(`  ${label}`);
    console.log(`    ${"horizon".padEnd(9)}${"tix".padStart(5)}${"sess".padStart(6)}${"booked".padStart(9)}${"held".padStart(9)}${"delta".padStart(9)}${"t".padStart(8)}${"bar".padStart(7)}`);
    for (const h of HORIZONS) {
      const a = block[`+${h}d`];
      if (!a) { console.log(`    +${h}d       too few rows`); continue; }
      console.log(`    ${("+" + h + "d").padEnd(9)}${String(a.tickets).padStart(5)}${String(a.sessions).padStart(6)}${String(a.bookedR).padStart(9)}${String(a.heldR).padStart(9)}${String(a.deltaR).padStart(9)}${String(a.t).padStart(8)}${String(a.bar).padStart(7)}${a.clears ? "   CLEARS" : ""}`);
    }
    console.log("");
  };
  show("HOLD WINNERS — green at the close, extended (the actual proposal)", out.holdWinners);
  show("HOLD ALL — stop flattening entirely (the upper bound; at 15:55 you cannot know which are winners)", out.holdAll);
  show("HOLD LOSERS — red at the close, extended (what the same rule does to the other half)", out.holdLosers);
  console.log(`  Exploratory. The hypothesis came from looking at these exits, so nothing here counts until a`);
  console.log(`  forward test is registered with an evidence start in the future.`);
})().catch((e) => { console.error("study failed:", e.message); process.exit(1); });
