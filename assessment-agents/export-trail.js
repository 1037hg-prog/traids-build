/**
 * TRAIDS Assessment Agents — compliance-trail exporter.
 *
 * Turns data/assessment-trail.jsonl (every multi-model assessment, logged) into a clean,
 * timestamped HTML report — the documented, repeatable review record an RIA / GIPS audit
 * wants: what was assessed, the overall verdict, each model's per-role verdict, and where the
 * models disagreed. Open in a browser or print to PDF.
 *
 * Run:  node export-trail.js            → writes assessment-log.html
 */
const fs = require("fs"), path = require("path");
const TRAIL = path.join(__dirname, "data", "assessment-trail.jsonl");
const OUT = path.join(__dirname, "assessment-log.html");

const esc = s => String(s == null ? "" : s).replace(/[&<>]/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;" }[c]));
const vColor = v => v === "FAIL" ? "#c0392b" : v === "CONCERNS" ? "#b9770a" : v === "PASS" ? "#1a8a4a" : "#5b6b7e";

if (!fs.existsSync(TRAIL)) { console.error("\n  No trail yet — run some assessments first (node selftest.js or POST /assess).\n"); process.exit(1); }
const recs = fs.readFileSync(TRAIL, "utf8").trim().split("\n").filter(Boolean).map(l => { try { return JSON.parse(l); } catch { return null; } }).filter(Boolean).reverse();

const dist = recs.reduce((m, r) => (m[r.overall] = (m[r.overall] || 0) + 1, m), {});
const disagreeRate = recs.length ? (recs.filter(r => (r.cross_model_disagreement || []).length).length / recs.length * 100) : 0;
const inSummary = r => typeof r.input === "object" ? (r.input.description || r.input.sym || JSON.stringify(r.input)).slice(0, 160) : String(r.input).slice(0, 160);

const cards = recs.map(r => `
  <div class="card">
    <div class="chead">
      <span class="verdict" style="background:${vColor(r.overall)}">${esc(r.overall)}</span>
      <span class="ts">${esc(r.ts)}</span>
      <span class="prov">models: ${esc((r.providers || []).join(", "))}</span>
      ${(r.cross_model_disagreement || []).length ? `<span class="split">⚠ split: ${esc(r.cross_model_disagreement.join(", "))}</span>` : ``}
      ${(r.no_response_roles || []).length ? `<span class="nr">no-response: ${esc(r.no_response_roles.join(", "))}</span>` : ``}
    </div>
    <div class="input">${esc(inSummary(r))}</div>
    <table>
      <tr><th>role</th><th>verdict</th><th>models</th><th>key risks</th></tr>
      ${(r.role_summary || []).map(rs => `<tr>
        <td>${esc(rs.role)}</td>
        <td style="color:${vColor(rs.verdict)};font-weight:700">${esc(rs.verdict)}${rs.disagreement ? ' <span class="dis">⚠</span>' : ''}</td>
        <td class="muted">${esc(rs.responded || "")}</td>
        <td class="muted">${esc((rs.risks || []).slice(0, 3).join("; "))}</td>
      </tr>`).join("")}
    </table>
  </div>`).join("");

const html = `<!doctype html><html><head><meta charset="utf-8"><title>TRAIDS — Assessment Log</title><style>
  body{font:13px/1.5 -apple-system,Segoe UI,Roboto,Arial,sans-serif;color:#11161f;background:#fff;margin:0;padding:0 24px 50px}
  .wrap{max-width:900px;margin:0 auto}
  header{padding:22px 0 12px;border-bottom:3px solid #00936f}
  h1{font-size:22px;margin:0 0 4px} .sub{color:#5b6b7e;font-size:12px}
  .stats{display:flex;gap:22px;flex-wrap:wrap;margin:16px 0}
  .stat{font-size:12px;color:#5b6b7e}.stat b{display:block;font-size:18px;color:#11161f}
  .card{border:1px solid #dfe5ec;border-radius:8px;padding:12px 14px;margin:12px 0}
  .chead{display:flex;gap:12px;align-items:center;flex-wrap:wrap;margin-bottom:8px}
  .verdict{color:#fff;font-weight:800;font-size:11px;padding:2px 10px;border-radius:20px}
  .ts{color:#5b6b7e;font-size:11px}.prov{color:#5b6b7e;font-size:11px}
  .split{color:#b9770a;font-weight:700;font-size:11px}.nr{color:#c0392b;font-size:11px}
  .input{background:#f6f8fa;border-radius:6px;padding:8px 10px;font-size:12px;margin-bottom:8px}
  table{width:100%;border-collapse:collapse;font-size:12px}
  th,td{text-align:left;padding:4px 8px;border-bottom:1px solid #eef1f5}
  th{color:#5b6b7e;font-size:10px;text-transform:uppercase}.muted{color:#5b6b7e}.dis{color:#b9770a}
  .foot{color:#5b6b7e;font-size:11px;margin-top:24px;border-top:1px solid #dfe5ec;padding-top:10px}
</style></head><body><div class="wrap">
<header><h1>TRAIDS — Assessment Log</h1>
<div class="sub">Multi-model red-team review record · ${recs.length} assessments · generated ${new Date().toISOString()}</div></header>
<div class="stats">
  ${Object.entries(dist).map(([k, v]) => `<div class="stat"><b style="color:${vColor(k)}">${v}</b>${esc(k)}</div>`).join("")}
  <div class="stat"><b>${disagreeRate.toFixed(0)}%</b>cross-model split</div>
</div>
<p class="sub">Risk-check &amp; documentation only — this panel does not generate edge. "Split" = models disagreed on a role (human-review flag).</p>
${cards}
<div class="foot">Generated by TRAIDS Assessment Agents from data/assessment-trail.jsonl. Paper/educational; not investment advice.</div>
</div></body></html>`;

fs.writeFileSync(OUT, html);
console.log(`\n  Wrote ${OUT}\n  ${recs.length} assessments · verdicts: ${Object.entries(dist).map(([k, v]) => k + " " + v).join(", ")} · ${disagreeRate.toFixed(0)}% had cross-model splits\n`);
