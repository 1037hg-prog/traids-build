#!/usr/bin/env node
/**
 * UNITS — every systemd unit of the W3 cell, generated from cell.cjs (real and SHADOW units from ONE template below, the shadow with
 * shadow=true), so systemd/ can never drift from the table. 2026-10-09 (docs/server/wave3-sleeves).
 *
 *   node docs/server/wave3-sleeves/units.cjs --write    (re)write systemd/*.{service,timer}
 *   node docs/server/wave3-sleeves/units.cjs --check    exit 0 when every file equals what expected() makes (and no stray file) AND every
 *                                                       service file on disk passes semanticIssues() (the gate side read from its name)
 *                                                       AND every timer file on disk passes timerIssues() (never replayed late)
 *
 * Template (plan v2 M5): User=traids · TZ=America/Denver · OnCalendar=… America/New_York · OnFailure=traids-alert@%n.service ·
 * EnvironmentFile=/etc/traids/w3-sleeves.env (the Alpaca PAPER pairs the units read: main and TV, root:traids 0640) · TRAIDS_ENV_FILE (the key file R316 and
 * R346 read) · a service that runs a schwab unit also: SCHWAB_MD_TOKEN_FILE=/home/traids/.traids/schwab-md-token.json and
 * EnvironmentFile=-/etc/traids/w2b-schwab.env (W2b's market-data-only app; optional: without it every schwab unit refuses / is skipped,
 * the alpaca units run) — the staged lib/schwab.js then takes its token from W2b's lib/schwab-md.js · per-unit flock: w3-run.cjs runs
 * every entry under /usr/bin/flock -w 600 data/w3-<x>.flock. The ops bot token for alerts is R309's real-tree backend/.env (notify.js).
 * ExecCondition:
 *   one-unit services   own-check.cjs <unit> server         (W1's /bin/sh wrapper: 0 run · 77 -> 1 skip · else 255 -> fail -> page)
 *   shared services     w3-run.cjs --any-owned <svc> server (the same wrapper: run while ANY of its units is server-owned; each entry is
 *                       then checked again inside w3-run.cjs / the runner, so a home-owned unit is never run by a shared service)
 * A SHADOW unit (traids-w3s-*) differs only in: the tree (/home/traids/w3-shadow), ExecCondition "<...> home", --shadow (the DRY form:
 * --live removed; nothing is sent), W3_OWNERSHIP_MAP (the REAL tree's map is the one authority), SyslogIdentifier, Description, the
 * timer's Unit= and — for r316a / r346a — the calendar (15:55:00 ET: their --dry decides at once; the live runner decides at 15:55:00).
 * Persistent=false everywhere: a fire the VPS missed is never replayed late (a late order is a wrong order).
 */
"use strict";
const fs = require("fs"), path = require("path");
const C = require("./cell.cjs");
const OC = require(path.join(__dirname, "..", "..", "..", "deploy", "server", "own-check.cjs"));
const SD = path.join(__dirname, "systemd"), NODE = "/usr/local/bin/node";
const RB = C.TREE.real + "/backend", RA = C.TREE.real + "/automation", SB = C.TREE.shadow + "/backend", SA = C.TREE.shadow + "/automation";
const MAP = RB + "/data/host-ownership.json";
const name = (svc, shadow, kind) => `traids-w3${shadow ? "s" : ""}-${svc}.${kind}`;

/** the ExecCondition of a shared service: w3-run.cjs --any-owned, wrapped exactly like own-check's (0 -> 0, 77 -> 1, else 255) */
function anyCondition(svc, want) {
  if (!C.SERVICES[svc] || (want !== "server" && want !== "home")) throw new Error("anyCondition: bad service / want");
  return `/bin/sh -c '${NODE} ${RB}/w3-run.cjs --any-owned ${svc} ${want}; c=$$?; if [ $$c -eq 0 ]; then exit 0; elif [ $$c -eq 77 ]; then exit 1; else exit 255; fi'`;
}
const conditionOf = (svc, want) => { const s = C.SERVICES[svc]; return s.kind === "unit" ? OC.conditionCommand(s.unit, want) : anyCondition(svc, want); };
const ET = (cal) => `OnCalendar=${cal} ${C.TZ}`;
function calendars(svc, shadow) {
  const s = C.SERVICES[svc], cal = shadow && s.shadowCalendar ? s.shadowCalendar : s.calendar, early = shadow && s.shadowEarly ? s.shadowEarly : s.early;
  return [...cal.map(ET), ...(early ? C.EARLY_CLOSE.map((d) => ET(`${d} ${early}:00`)) : [])];
}
function service(svc, shadow) {
  const s = C.SERVICES[svc], B = shadow ? SB : RB, A = shadow ? SA : RA, want = shadow ? "home" : "server";
  const exec = s.kind === "runner" ? `${NODE} ${A}/close-arm-runner-vps.cjs --service ${svc}${shadow ? " --shadow" : " --by task"}` : `${NODE} ${B}/w3-run.cjs --service ${svc}${shadow ? " --shadow" : ""}`;
  const units = C.unitsOf(svc).map(C.short).join(" ");
  return [
    `# TRAIDS W3 ${shadow ? "SHADOW " : ""}(server migration, docs/server/wave3-sleeves; generated by units.cjs from cell.cjs) — ${s.what}.`,
    `# Units: ${units}. ${shadow ? "DRY forms only (--live removed: nothing is sent) for the units HOME owns, in the shadow tree " + C.TREE.shadow + " (never pulled); compare.cjs reads its logs." : "Runs an entry only while home's map gives its unit to the server (" + (s.kind === "unit" ? "ExecCondition" : "ExecCondition for any unit, then per entry inside") + ")."}`,
    "# A nonzero exit pages through traids-alert@ (the same failure re-pages at most every 3 h).",
    "[Unit]",
    `Description=TRAIDS W3 ${shadow ? "SHADOW " : ""}${svc} (${shadow ? "dry; runs only while home-owned" : "runs only while server-owned"})`,
    "After=network-online.target time-sync.target",
    "Wants=network-online.target",
    "OnFailure=traids-alert@%n.service",
    "",
    "[Service]",
    "Type=oneshot",
    "User=traids",
    "Group=traids",
    `WorkingDirectory=${B}`,
    "Environment=TZ=America/Denver",
    `Environment=W3_TREE=${shadow ? "shadow" : "real"}`,
    `Environment=W3_OWNERSHIP_MAP=${MAP}`,
    `Environment=TRAIDS_ENV_FILE=${C.ENV.sleeves}`,
    `EnvironmentFile=${C.ENV.sleeves}`,
    ...(C.hasSchwab(svc) ? [`Environment=SCHWAB_MD_TOKEN_FILE=${C.ENV.schwabMdToken}`, `EnvironmentFile=-${C.ENV.schwabMdEnv}`] : []),
    `ExecCondition=${conditionOf(svc, want)}`,
    `ExecStart=${exec}`,
    `SyslogIdentifier=traids-w3${shadow ? "s" : ""}-${svc}`,
    `TimeoutStartSec=${s.timeoutMin}min`,
    "TimeoutStopSec=60s",
    "KillMode=control-group",
    "MemoryMax=768M",
    "NoNewPrivileges=yes",
    "PrivateTmp=yes",
    "ProtectSystem=full",
    "",
  ].join("\n");
}
function timer(svc, shadow) {
  const s = C.SERVICES[svc];
  return [
    `# TRAIDS W3 ${shadow ? "SHADOW " : ""}timer (generated by units.cjs from cell.cjs) — ${s.what}. Times are America/New_York, so they follow DST`,
    "# exactly as the home tasks' local MT triggers did. Persistent=false: a missed fire is never replayed late.",
    "[Unit]",
    `Description=TRAIDS W3 ${shadow ? "SHADOW " : ""}${svc} timer`,
    "",
    "[Timer]",
    ...calendars(svc, shadow),
    "AccuracySec=1s",
    "RandomizedDelaySec=0",
    "Persistent=false",
    `Unit=${name(svc, shadow, "service")}`,
    "",
    "[Install]",
    "WantedBy=timers.target",
    "",
  ].join("\n");
}
function expected() {
  const m = {};
  for (const svc of Object.keys(C.SERVICES)) {
    m[name(svc, false, "service")] = service(svc, false); m[name(svc, false, "timer")] = timer(svc, false);
    if (!C.SERVICES[svc].noShadow) { m[name(svc, true, "service")] = service(svc, true); m[name(svc, true, "timer")] = timer(svc, true); }
  }
  return m;
}
/**
 * SEMANTIC CHECK of unit files, independent of service() above (a generator that gated REAL services on "home", consistently
 * regenerated, would pass a files == generator check): the gate side is read from the FILE NAME — traids-w3-* runs only while
 * server-owned, traids-w3s-* only while home-owned — and the condition is built from own-check.cjs's own conditionCommand (one-unit
 * services) or the any-owned wrapper with that literal side. Also the tree, W3_TREE and --shadow follow the file name.
 * files: { name: text } -> [{ name, why }] (empty = every service file right)
 */
function semanticIssues(files) {
  const out = [];
  for (const [n, text] of Object.entries(files)) {
    const m = /^traids-w3(s?)-(.+)\.service$/.exec(n); if (!m) continue;
    const shadow = m[1] === "s", svc = m[2], s = C.SERVICES[svc];
    if (!s) { out.push({ name: n, why: `no service ${svc} in cell.cjs` }); continue; }
    const side = shadow ? "home" : "server", lines = String(text).split("\n"), one = (k) => lines.filter((l) => l.startsWith(k + "="));
    const cond = one("ExecCondition"), want = `ExecCondition=${s.kind === "unit" ? OC.conditionCommand(s.unit, side) : `/bin/sh -c '${NODE} ${RB}/w3-run.cjs --any-owned ${svc} ${side}; c=$$?; if [ $$c -eq 0 ]; then exit 0; elif [ $$c -eq 77 ]; then exit 1; else exit 255; fi'`}`;
    if (cond.length !== 1 || cond[0] !== want) out.push({ name: n, why: `ExecCondition is not the ${side} gate (${s.kind === "unit" ? `own-check ${s.unit} ${side}` : `w3-run --any-owned ${svc} ${side}`}): ${cond.join(" | ").slice(0, 160) || "none"}` });
    const ex = one("ExecStart"), tree = shadow ? C.TREE.shadow : C.TREE.real;
    if (ex.length !== 1 || !ex[0].includes(` ${tree}/`) || /--shadow\b/.test(ex[0]) !== shadow || (shadow && !ex[0].endsWith(" --shadow")) || (!shadow && !/ --by task$|w3-run\.cjs --service \S+$/.test(ex[0]))) out.push({ name: n, why: `ExecStart does not run the ${shadow ? "shadow (--shadow, " + tree + ")" : "real (" + tree + ", no --shadow)"} form: ${ex.join(" | ").slice(0, 160)}` });
    const wt = lines.filter((l) => l.startsWith("Environment=W3_TREE=")), wd = one("WorkingDirectory");
    if (wt.length !== 1 || wt[0] !== `Environment=W3_TREE=${shadow ? "shadow" : "real"}` || wd.length !== 1 || wd[0] !== `WorkingDirectory=${tree}/backend`) out.push({ name: n, why: `W3_TREE / WorkingDirectory do not say the ${shadow ? "shadow" : "real"} tree` });
  }
  return out;
}
/**
 * SEMANTIC CHECK of timer files, independent of timer() above ("a late order is a wrong order"): every traids-w3*.timer holds EXACTLY ONE
 * each of Persistent=false, AccuracySec=1s and RandomizedDelaySec=0 — a fire the VPS missed (down, rebooting) is never replayed at boot,
 * and a fire is never spread or delayed — and no other value of those three keys.
 * files: { name: text } -> [{ name, why }] (empty = every timer file right)
 */
const TIMER_MUST = ["Persistent=false", "AccuracySec=1s", "RandomizedDelaySec=0"];
function timerIssues(files) {
  const out = [];
  for (const [n, text] of Object.entries(files)) {
    if (!/^traids-w3s?-.+\.timer$/.test(n)) continue;
    const lines = String(text).split("\n").map((l) => l.trim());
    for (const want of TIMER_MUST) {
      const key = want.slice(0, want.indexOf("=") + 1), have = lines.filter((l) => l.startsWith(key));
      if (have.length !== 1 || have[0] !== want) out.push({ name: n, why: `wants exactly one "${want}" (a missed fire is never replayed late, never spread): ${have.join(" | ") || "none"}` });
    }
  }
  return out;
}
const ALL_UNITS = Object.keys(expected());
const REAL_UNITS = ALL_UNITS.filter((u) => /^traids-w3-/.test(u)), SHADOW_UNITS = ALL_UNITS.filter((u) => /^traids-w3s-/.test(u));
/** the shadow timers that need the Schwab market-data token on the VPS (one-unit services of a schwab unit) */
const SCHWAB_SHADOW_TIMERS = SHADOW_UNITS.filter((u) => u.endsWith(".timer")).filter((u) => { const svc = u.replace(/^traids-w3s-/, "").replace(/\.timer$/, ""); const s = C.SERVICES[svc]; return s.kind === "unit" && C.UNITS[s.unit].group === "schwab"; });

if (require.main === module) {
  const a = process.argv.slice(2);
  if (a.length === 1 && a[0] === "--write") { fs.mkdirSync(SD, { recursive: true }); for (const [f, t] of Object.entries(expected())) { fs.writeFileSync(path.join(SD, f), t); } console.log(`written ${ALL_UNITS.length} unit files in systemd/`); process.exitCode = 0; }
  else if (a.length === 1 && a[0] === "--check") {
    let bad = 0; const want = expected();
    for (const [f, t] of Object.entries(want)) { let cur = null; try { cur = fs.readFileSync(path.join(SD, f), "utf8"); } catch { cur = null; } const ok = cur === t; if (!ok) { bad++; console.log(`DIFF systemd/${f}`); } else console.log(`ok   systemd/${f}`); }
    for (const f of fs.existsSync(SD) ? fs.readdirSync(SD) : []) if (!(f in want)) { bad++; console.log(`DIFF systemd/${f} (not generated)`); }
    // semantic: the files ON DISK (what deploy.cjs installs), judged without the generator
    const disk = Object.fromEntries((fs.existsSync(SD) ? fs.readdirSync(SD) : []).filter((f) => /\.service$/.test(f)).map((f) => [f, fs.readFileSync(path.join(SD, f), "utf8")]));
    const iss = semanticIssues(disk);
    for (const f of Object.keys(disk).sort()) { const i = iss.filter((x) => x.name === f); if (i.length) { bad++; for (const x of i) console.log(`DIFF semantic systemd/${f}: ${x.why}`); } else console.log(`ok   semantic systemd/${f}: gated ${/^traids-w3s-/.test(f) ? "home (shadow tree, --shadow)" : "server (real tree)"}`); }
    // the semantic check catches a generator that swapped the sides: every real file regated on "home", every shadow file on "server"
    const swapped = Object.fromEntries(Object.entries(want).filter(([f]) => /\.service$/.test(f)).map(([f, t]) => { const svc = f.replace(/^traids-w3s?-/, "").replace(/\.service$/, ""), sh = /^traids-w3s-/.test(f); return [f, t.split("\n").map((l) => (l.startsWith("ExecCondition=") ? `ExecCondition=${conditionOf(svc, sh ? "server" : "home")}` : l)).join("\n")]; }));
    const caught = semanticIssues(swapped), nSvc = Object.keys(swapped).length;
    if (nSvc === 20 && Object.keys(swapped).every((f) => caught.some((x) => x.name === f && /ExecCondition is not the (home|server) gate/.test(x.why)))) console.log(`ok   semantic: all ${nSvc} service files with their gate side swapped (a real unit gated on 'home', a shadow on 'server') are each flagged`);
    else { bad++; console.log(`DIFF semantic: a swapped gate side was NOT flagged (${caught.length} of ${nSvc})`); }
    // KNOWN ANSWER (the files on disk): every traids-w3s-*.service ExecStart ENDS in " --shadow" (the runner's and w3-run's) and no traids-w3-*.service
    // carries it — a shadow service without it would run the REAL (--live) form in the shadow tree
    { const exOf = (f) => disk[f].split("\n").filter((l) => l.startsWith("ExecStart=")), sh = Object.keys(disk).filter((f) => /^traids-w3s-/.test(f)), re = Object.keys(disk).filter((f) => /^traids-w3-/.test(f));
      const shBad = sh.filter((f) => !(exOf(f).length === 1 && exOf(f)[0].endsWith(" --shadow"))), reBad = re.filter((f) => !(exOf(f).length === 1 && !exOf(f)[0].includes("--shadow")));
      if (sh.length === 9 && re.length === 11 && !shBad.length && !reBad.length) console.log(`ok   semantic: every traids-w3s-*.service ExecStart ends in " --shadow" (${sh.length} files: ${sh.filter((f) => /close-arm-runner-vps\.cjs/.test(exOf(f)[0])).length} runner, ${sh.filter((f) => /w3-run\.cjs/.test(exOf(f)[0])).length} w3-run); no traids-w3-*.service carries it (${re.length})`);
      else { bad++; console.log(`DIFF semantic: a shadow service's ExecStart does not end in " --shadow", or a real one carries it: ${[...shBad, ...reBad].join(", ") || `${sh.length} shadow / ${re.length} real service files (want 9 / 11)`}`); }
      // ... and the semantic check itself flags a shadow service that lost it (every shadow file as generated, the flag removed)
      const gen = Object.entries(want).filter(([f]) => /^traids-w3s-.+\.service$/.test(f)), lost = Object.fromEntries(gen.map(([f, t]) => [f, t.split("\n").map((l) => (l.startsWith("ExecStart=") ? l.replace(/ --shadow$/, "") : l)).join("\n")])), lc = semanticIssues(lost);
      if (gen.length === 9 && gen.every(([f, t]) => lost[f] !== t && lc.some((x) => x.name === f && /ExecStart does not run the shadow/.test(x.why)))) console.log(`ok   semantic: all ${gen.length} shadow service files with --shadow removed from ExecStart (they would run the REAL form in the shadow tree) are each flagged`);
      else { bad++; console.log(`DIFF semantic: a shadow service without --shadow was NOT flagged (${lc.length} of ${gen.length})`); } }
    // timers: the files ON DISK, judged without the generator — exactly one Persistent=false, AccuracySec=1s, RandomizedDelaySec=0 each
    const tdisk = Object.fromEntries((fs.existsSync(SD) ? fs.readdirSync(SD) : []).filter((f) => /\.timer$/.test(f)).map((f) => [f, fs.readFileSync(path.join(SD, f), "utf8")]));
    const tiss = timerIssues(tdisk);
    for (const f of Object.keys(tdisk).sort()) { const i = tiss.filter((x) => x.name === f); if (i.length) { bad++; for (const x of i) console.log(`DIFF semantic systemd/${f}: ${x.why}`); } else console.log(`ok   semantic systemd/${f}: ${TIMER_MUST.join(", ")} (exactly once each)`); }
    // ... and the timer check flags each way a timer could replay or spread a fire: Persistent=true, the line gone, a second line, a delay
    { const tw = Object.entries(want).filter(([f]) => /\.timer$/.test(f)), nT = tw.length, GOOD = "AccuracySec=1s\nRandomizedDelaySec=0\nPersistent=false\n";
      const muts = [["Persistent=true", (t) => t.replace("Persistent=false\n", "Persistent=true\n")], ["the Persistent= line removed", (t) => t.replace("Persistent=false\n", "")], ["a second line Persistent=true", (t) => t.replace("Persistent=false\n", "Persistent=false\nPersistent=true\n")],
        ["AccuracySec=1min", (t) => t.replace("AccuracySec=1s\n", "AccuracySec=1min\n")], ["RandomizedDelaySec=30", (t) => t.replace("RandomizedDelaySec=0\n", "RandomizedDelaySec=30\n")]];
      const base = tw.map(([f, t]) => [f, t.includes(GOOD) ? t : t.replace(/^(AccuracySec|RandomizedDelaySec|Persistent)=.*\n/gm, "").replace("[Timer]\n", "[Timer]\n" + GOOD)]);   // each mutation starts from a RIGHT timer, whatever the generator made
      const missed = muts.filter(([, fn]) => !base.every(([f, t]) => fn(t) !== t && timerIssues({ [f]: fn(t) }).length >= 1)).map(([n]) => n);
      if (nT === 20 && !missed.length && timerIssues(Object.fromEntries(base)).length === 0) console.log(`ok   semantic: all ${nT} timer files are each flagged with ${muts.map(([n]) => n).join(" / ")} (a missed fire replayed at boot, or a fire spread, is a late order)`);
      else { bad++; console.log(`DIFF semantic: a timer that could replay or spread a fire was NOT flagged (${missed.join(", ") || nT + " timers, want 20"})`); } }
    process.exitCode = bad ? 1 : 0;
  } else { console.log("usage: node units.cjs --write | --check"); process.exitCode = 2; }
}
module.exports = { expected, semanticIssues, timerIssues, TIMER_MUST, anyCondition, conditionOf, calendars, ALL_UNITS, REAL_UNITS, SHADOW_UNITS, SCHWAB_SHADOW_TIMERS, name, RB, RA, SB, SA, MAP, NODE };
